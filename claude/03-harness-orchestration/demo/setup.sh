cat > .claude/hooks/_lib.sh <<'EOF'
# 共通: marker の置き場（セッション単位、best effort）
marker_dir() { echo "${TMPDIR:-/tmp}/claude-hooks-demo-$(id -u)"; }
session_of() { jq -r '.session_id // "unknown"' <<<"$1"; }
EOF
cat > .claude/hooks/bash-guard.sh <<'EOF'
#!/usr/bin/env bash
# PreToolUse (Bash): 機械的に白黒がつく禁止事項だけを止める。拒否は exit 2 + stderr で
# 「なぜ」「正しい代替手順」「出典」を返す。
set -euo pipefail
input=$(cat)
cmd=$(jq -r '.tool_input.command // ""' <<<"$input")
branch=$(git -C "${CLAUDE_PROJECT_DIR:-.}" branch --show-current 2>/dev/null || echo "")

if [[ "$cmd" =~ git[[:space:]]+(commit|push) ]] && [[ "$branch" == "main" ]]; then
  echo "拒否: main ブランチ上での git commit / push は禁止です（docs/design.md「作業の原則」）。" >&2
  echo "代替: /plan-task で feature ブランチを切ってから commit してください。" >&2
  exit 2
fi
if [[ "$cmd" =~ (sed[[:space:]]+-i|>|tee)[^|]*dist/ ]]; then
  echo "拒否: dist/ は生成物です。手で書き換えず npm run build で再生成してください（docs/design.md）。" >&2
  exit 2
fi
exit 0
EOF
cat > .claude/hooks/file-guard.sh <<'EOF'
#!/usr/bin/env bash
# PreToolUse (Edit|Write): 生成物への書き込みと、秘密らしき文字列の混入を止める。
set -euo pipefail
input=$(cat)
path=$(jq -r '.tool_input.file_path // ""' <<<"$input")
content=$(jq -r '.tool_input.content // .tool_input.new_string // ""' <<<"$input")

case "$path" in
  */dist/*|dist/*)
    echo "拒否: $path は生成物です。scripts/build.js を直して npm run build で再生成してください（docs/design.md）。" >&2
    exit 2 ;;
esac
# 検出パターン（実トークンではない）。必要に応じて自分の環境の形式を足す
if grep -Eq '(ghp_[A-Za-z0-9]{20,}|AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY-----)' <<<"$content"; then
  echo "拒否: 書き込み内容にトークンか秘密鍵らしき文字列があります。環境変数か secret manager に置いてください（docs/design.md）。" >&2
  exit 2
fi
exit 0
EOF
cat > .claude/hooks/track-edit.sh <<'EOF'
#!/usr/bin/env bash
# PostToolUse (Edit|Write): src/ を編集したら dirty marker を置く（内部状態）
set -euo pipefail
. "$(dirname "$0")/_lib.sh"
input=$(cat)
path=$(jq -r '.tool_input.file_path // ""' <<<"$input")
case "$path" in
  */src/*|src/*) mkdir -p "$(marker_dir)"; touch "$(marker_dir)/$(session_of "$input").src-dirty" ;;
esac
exit 0
EOF
cat > .claude/hooks/track-test-run.sh <<'EOF'
#!/usr/bin/env bash
# PostToolUse (Bash): npm test が成功したら dirty marker を消す（内部状態）
set -euo pipefail
. "$(dirname "$0")/_lib.sh"
input=$(cat)
cmd=$(jq -r '.tool_input.command // ""' <<<"$input")
out=$(jq -r '.tool_response.stdout // ""' <<<"$input")
if [[ "$cmd" == *"npm test"* ]] && [[ "$out" == *"fail 0"* ]]; then
  rm -f "$(marker_dir)/$(session_of "$input").src-dirty"
fi
exit 0
EOF
cat > .claude/hooks/stop-test-reminder.sh <<'EOF'
#!/usr/bin/env bash
# Stop: src/ を編集したままテスト未成功で応答を結ぼうとしたら、1 回だけ block して促す（soft）。
# 前回の催促以降に新しい編集が無ければ再催促しない。stop_hook_active で無限ループを避ける。
set -euo pipefail
. "$(dirname "$0")/_lib.sh"
input=$(cat)
[ "$(jq -r '.stop_hook_active // false' <<<"$input")" = "true" ] && exit 0
s=$(session_of "$input")
dirty="$(marker_dir)/$s.src-dirty"; reminded="$(marker_dir)/$s.reminded"
[ -f "$dirty" ] || exit 0
if [ -f "$reminded" ] && [ ! "$dirty" -nt "$reminded" ]; then exit 0; fi
touch "$reminded"
jq -n '{decision: "block", reason: "src/ を編集した後、npm test の成功を確認していません。区切りとして npm test を実行して結果を報告するか、実行を見送る理由をユーザーに明示してから応答を結んでください（docs/design.md）。"}'
exit 0
EOF
cat > .claude/hooks/session-start.sh <<'EOF'
#!/usr/bin/env bash
# SessionStart: 現在ブランチと未完了 plan を注入する（状況提示。stdout が文脈に入る）
set -euo pipefail
cd "${CLAUDE_PROJECT_DIR:-.}"
b=$(git branch --show-current 2>/dev/null || echo "?")
echo "現在ブランチ: $b$([ "$b" = main ] && echo '（main では commit 禁止。/plan-task で分岐）')"
ls dev/tasks/*.md 2>/dev/null | sed 's/^/未完了の plan: /' || true
EOF
