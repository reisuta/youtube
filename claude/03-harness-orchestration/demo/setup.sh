  return `hello, ${name}`;
}
EOF
cat > test/app.test.js <<'EOF'
import { test } from "node:test";
import assert from "node:assert/strict";
import { greet } from "../src/app.js";
test("greet", () => assert.equal(greet("world"), "hello, world"));
EOF
echo '// generated by scripts/build.js — do not edit' > dist/app.js
echo 'console.log("build")' > scripts/build.js

# ---- 真実源（設計文書）と CLAUDE.md（40 行以内） ----
cat > docs/design.md <<'EOF'
# 設計文書（真実源）

## 作業の原則
- main に直接 commit / push しない。作業は feature ブランチ + PR。
- dist/ は生成物。手で編集せず scripts/build.js で再生成する。
- src/ を編集したら `npm test` を通してから応答を結ぶ。
- 秘密情報（トークン、鍵）をリポジトリに書かない。
- 設計書に無い機能を「良かれと思って」足さない。必要なら止まって聞く。

## やらないこと
- テストの削除や skip で通す。
- 生成物 dist/ を手で直す。
EOF
