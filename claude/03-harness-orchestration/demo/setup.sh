# 品質ゲート (quality-gate)

真実源: docs/design.md「作業の原則」。規約の本文はここに複製しない。

## 手順
1. `npm test` を実行する。失敗したら原因を直す。**テストの削除や skip で通さない**。
2. `npm run build` で dist/ を再生成し、`git status` で dist/ 以外に想定外の変更が無いか見る。
3. `git diff` を読み、設計書に無い変更が混ざっていないか確認する。あれば **ユーザーに確認する**（勝手に進めない）。
4. 結果を「成功 / 失敗」で明言する。失敗時は段名・対象ファイル・エラー文を添える。

## やらないこと
- main への commit / push（hook が止めるが、そもそも試みない）。
- dist/ の手編集。
EOF
