cat > .claude/workflows/review-changes.js <<'EOF'
export const meta = {
  name: 'review-changes',
  description: '変更ファイルをレビューし、指摘を別のエージェントに検証させる',
  phases: [{ title: 'Review' }, { title: 'Verify' }],
}
const changed = await agent('git diff --name-only main を実行し、変更ファイルの一覧を返す。', {
  schema: { type: 'object', required: ['files'], properties: { files: { type: 'array', items: { type: 'string' } } } },
})
const results = await pipeline(
  changed.files,
  f => agent(`${f} を docs/design.md の原則と照らしてレビューし、指摘を列挙する。`, { label: `review:${f}`, phase: 'Review' }),
  review => agent(`次の指摘が本当に問題か、反証を探して検証する: ${review}`, { label: 'verify', phase: 'Verify' }),
)
return results.filter(Boolean)
EOF
cat > scripts/nightly.sh <<'EOF'
#!/usr/bin/env bash
# 夜間に無人で回す例。--bare はホストの hook や CLAUDE.md を読まない（環境差が消える）が、
# プロジェクトの hook も読まないので --settings で明示して渡す。-p の既定は手動なので auto を指定し、
# 人間が答えられないプロンプトは拒否として扱う。結果は JSON で受けて機械で読む。
set -euo pipefail
export ANTHROPIC_API_KEY="${ANTHROPIC_API_KEY:?set in CI secrets}"
result=$(claude --bare -p "依存関係を更新して npm test を通す。通らなければ何も変更せず理由を報告する" \
  --settings .claude/settings.json \
  --permission-mode auto --permission-prompts none \
  --allowedTools "Bash(npm *),Read,Edit" \
  --output-format json)
echo "$result" | jq -r '.result'
echo "$result" | jq -r '"cost: \(.total_cost_usd) USD"'
EOF
