#!/usr/bin/env bash
# 動画の実演用サンプルプロジェクトを /tmp/harness-demo に作り直す。
#   bash demo/setup.sh            作る（毎回削除して作り直す）
#   bash demo/setup.sh dirty      作ったうえで「src を編集したがテスト未実行」の marker を置く
# 触るのは /tmp/harness-demo と $TMPDIR/claude-hooks-demo-<uid>/ だけ。実ホーム・実リポジトリ・~/.claude には触れない。
# 必要なもの: bash、jq、git。（tape を撮るなら vhs と tree）
set -euo pipefail
D=/tmp/harness-demo
rm -rf "$D" "${TMPDIR:-/tmp}/claude-hooks-demo-$(id -u)"
mkdir -p "$D"/{src,test,dist,docs,dev/tasks,scripts,.claude/{hooks,skills/quality-gate,skills/plan-task,rules,agents,workflows}}
cd "$D"
git init -q -b main

cat > package.json <<'EOF'
{
  "name": "harness-demo",
  "private": true,
  "scripts": { "test": "node --test", "build": "node scripts/build.js" }
}
EOF
cat > src/app.js <<'EOF'
