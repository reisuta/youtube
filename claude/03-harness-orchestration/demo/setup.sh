---
name: quality-gate
description: 区切りごとの品質ゲート。テスト・ビルド・差分の自己レビューを決まった順に行い、結果を成功 / 失敗で報告する。「区切り」「PR 前」と言われたら使う。
disable-model-invocation: false
allowed-tools: Bash(npm test) Bash(npm run build) Bash(git diff *) Bash(git status *)
